def test_the_curved_error_is_a_not_implemented_error_with_its_key():
    import pickle

    err = gfem.CurvedMeshUnsupportedError("2d_mesh", "no path; use ElementOrder 1")
    assert isinstance(err, NotImplementedError)
    assert err.feature == "2d_mesh"
    assert str(err) == "no path; use ElementOrder 1"
    copy = pickle.loads(pickle.dumps(err))  # noqa: S301
    assert (copy.feature, str(copy)) == (err.feature, str(err))


