def test_a_mix_of_first_and_second_order_cells_raises(tmp_path):
    raw = meshio.read(DATA / "octant_order2.msh")
    cells, physical, geometrical = [], [], []
    for block, phys, geom in zip(
        raw.cells,
        raw.cell_data["gmsh:physical"],
        raw.cell_data["gmsh:geometrical"],
        strict=True,
    ):
        # the faces lose their mid nodes: first-order triangles under tetra10
        data = block.data[:, :3] if block.type == "triangle6" else block.data
        cells.append(("triangle" if block.type == "triangle6" else block.type, data))
        physical.append(phys)
        geometrical.append(geom)
    mixed = meshio.Mesh(
        raw.points,
        cells,
        cell_data={"gmsh:physical": physical, "gmsh:geometrical": geometrical},
        field_data=raw.field_data,
    )
    path = tmp_path / "mixed.msh"
    meshio.write(path, mixed, file_format="gmsh22", binary=False)
    with pytest.raises(ValueError, match=r"first- and second-order") as err:
        gfem.Mesh.from_gmsh(path, length_unit="m")
    assert "ElementOrder 2" in str(err.value)
    assert "ElementOrder 1" in str(err.value)


def _plane_file(tmp_path, order):
    import gmsh

    path = tmp_path / f"plane{order}.msh"
    gmsh.initialize()
    try:
        gmsh.option.setNumber("General.Terminal", 0)
        gmsh.model.add("p")
        gmsh.model.occ.addDisk(0, 0, 0, 1, 1)
        gmsh.model.occ.synchronize()
        gmsh.model.addPhysicalGroup(2, [1], 1, "disk")
        gmsh.model.addPhysicalGroup(
            1, [t for _, t in gmsh.model.getEntities(1)], 2, "rim"
        )
        gmsh.option.setNumber("Mesh.MeshSizeMax", 0.5)
        gmsh.option.setNumber("Mesh.ElementOrder", order)
        gmsh.option.setNumber("Mesh.MshFileVersion", 4.1)
        gmsh.model.mesh.generate(2)
        gmsh.write(str(path))
    finally:
        gmsh.finalize()
    return path


def test_a_curved_2d_file_raises_with_the_2d_mesh_key(tmp_path):
    pytest.importorskip("gmsh")
    path = _plane_file(tmp_path, 2)
    with pytest.raises(gfem.CurvedMeshUnsupportedError) as err:
        gfem.Mesh.from_gmsh(path, length_unit="m")
    assert err.value.feature == "2d_mesh"
    assert "ElementOrder 1" in str(err.value)


def test_a_curved_cross_section_raises_with_the_cross_section_key(tmp_path):
    pytest.importorskip("gmsh")
