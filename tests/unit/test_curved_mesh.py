def test_with_nodes_on_a_curved_mesh_raises_on_a_folded_element(octant):
    nodes = np.array(octant.nodes)
    t = octant._topology
    centre = nodes[t.volume_elements[0]].mean(axis=0)
    for m in t.volume_midnodes[0]:
        nodes[m] = centre + 2.0 * (centre - nodes[m])
    with pytest.raises(gfem.MeshQualityError):
        octant.with_nodes(nodes)


def test_with_nodes_on_a_curved_mesh_accepts_a_small_move(octant):
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        moved = octant.with_nodes(np.asarray(octant.nodes) * 1.01)
    assert moved.curved


