# --- the NGSolve build -------------------------------------------------------


def _volume(mesh):
    built = to_ngsolve(mesh)
    return ngs.Integrate(1, built.mesh) * built.scale**3


def test_curved_elements_integrate_the_sphere_volume_and_faceted_ones_do_not(
    octant, octant_straight
):
    # Octant volume pi / 6. Measured relative errors: curved 2e-5 (the quadratic
    # map's error at h = 0.2 is O(h^3)), faceted 1.3e-2. The bounds are the
    # ticket's 1e-3 and 1e-2, each about 50x and 0.8x the measured values.
    exact = math.pi / 6
    assert abs(_volume(octant) - exact) / exact < 1e-3
    assert abs(_volume(octant_straight) - exact) / exact > 1e-2


def test_the_built_mesh_numbers_corners_first_and_node_order_maps_them_back(octant):
    built = to_ngsolve(octant)
    t = octant._topology
    corners = np.unique(t.volume_elements)
    assert built.mesh.nv == len(corners)
    np.testing.assert_array_equal(built.node_order, corners)
    # NGSolve vertex i sits at gfem node node_order[i] (in the file's unit)
    got = np.array([built.mesh.vertices[i].point for i in range(built.mesh.nv)])
    np.testing.assert_allclose(
        got, np.asarray(octant.nodes)[built.node_order] / built.scale
    )


def test_the_curved_boundary_area_is_the_sphere_s_to_second_order(
    octant, octant_straight
):
    # Wall area pi / 2 (an octant of 4 pi): the same bound as the volume.
    def wall(mesh):
        built = to_ngsolve(mesh)
        return ngs.Integrate(1, built.mesh.Boundaries("wall")) * built.scale**2

    exact = math.pi / 2
    assert abs(wall(octant) - exact) / exact < 1e-3
    assert abs(wall(octant_straight) - exact) / exact > 5e-3


# --- the solve ---------------------------------------------------------------

QUARTER_COAX = gfem.Electrostatic(terminals={"in": "inner"}, ground="outer")


def _coax_capacitance(name):
    mesh = _read(name, unit="m")
    model = gfem.Model(mesh, materials={"fill": gfem.Material(eps_r=1.0)})
    return float(gfem.solve(model, QUARTER_COAX).capacitance[0, 0])


def test_a_curved_coax_capacitance_beats_the_faceted_twin():
    # Quarter coax of length 1 m: C = eps0 (pi / 2) / ln(2). The faceted
    # annulus has the wrong area, so its error stays at the geometry level
    # (a few percent at size 0.5), while the curved walls leave only the
    # P2 discretisation error. Requiring the curved error to be below a third
    # of the faceted one (measured ratio is far larger) is robust to the solver.
    exact = EPS0 * (math.pi / 2) / math.log(2)
    straight = abs(_coax_capacitance("coax_order1") - exact) / exact
    curved = abs(_coax_capacitance("coax_order2") - exact) / exact
    assert straight > 5e-3
    assert curved < straight / 3


# --- job files ----------------------------------------------------------------


def test_a_curved_mesh_with_no_file_round_trips_through_a_job(octant, tmp_path):
    from gfem.mesh import _mesh_sha256, _same_topology

    memory = gfem.Mesh(octant.nodes, dataclasses.replace(octant._topology, source=None))
    model = gfem.Model(memory, materials={"ball": gfem.Material(eps_r=1.0)})
    problem = gfem.Electrostatic(terminals={"w": "wall"}, ground="sym")
    path = gfem.Job(model, problem).to_json(tmp_path / "job.json")
    back = gfem.Job.from_json(path).model.mesh
    assert back.curved
    assert _same_topology(memory, back)
    assert _mesh_sha256(memory) == _mesh_sha256(back)
    np.testing.assert_array_equal(
        back._topology.volume_midnodes, memory._topology.volume_midnodes
    )
    np.testing.assert_array_equal(
        back._topology.surface_midnodes, memory._topology.surface_midnodes
    )


def test_a_curved_mesh_job_that_names_a_file_rereads_it(octant, tmp_path):
    model = gfem.Model(octant, materials={"ball": gfem.Material(eps_r=1.0)})
    problem = gfem.Electrostatic(terminals={"w": "wall"}, ground="sym")
    path = gfem.Job(model, problem).to_json(tmp_path / "job.json")
    assert gfem.Job.from_json(path).model.mesh.curved


# --- quality -------------------------------------------------------------------


def _fold(name, tmp_path):
    """The order-2 mesh with one tetrahedron's mid-edge nodes pushed through it."""
    raw = meshio.read(DATA / f"{name}.msh")
    tets = raw.cells_dict["tetra10"]
    points = raw.points.copy()
    centre = points[tets[0, :4]].mean(axis=0)
    # all six mid nodes of tet 0 go to its centroid's far side: the quadratic
    # map folds (its Jacobian changes sign inside the element)
    for m in tets[0, 4:]:
        points[m] = centre + 2.0 * (centre - points[m])
    raw.points = points
    path = tmp_path / "folded.msh"
    meshio.write(path, raw, file_format="gmsh", binary=False)
    return path


def test_a_folded_curved_tetrahedron_raises_naming_high_order_optimize(tmp_path):
    path = _fold("octant_order2", tmp_path)
    with pytest.raises(gfem.MeshQualityError, match=r"HighOrderOptimize 1"):
        gfem.Mesh.from_gmsh(path, length_unit="m")


def _chord_straight(mesh):
    """``mesh`` with every volume mid-edge node moved onto its chord midpoint."""
    t = mesh._topology
    x = np.array(mesh.nodes)
    corners = x[t.volume_elements]
    for k, (a, b) in enumerate(_TET_EDGES):
        x[t.volume_midnodes[:, k]] = (corners[:, a] + corners[:, b]) / 2
    return gfem.Mesh(x, t)


def test_quality_of_a_chord_straight_curved_mesh_is_the_straight_meshs(
    octant, octant_straight
):
    # Same corners and element order in both files. Each value is a few dozen
    # flops on O(1) numbers, so the two computations (twenty lattice points
    # against one) differ by at most ~50 eps = 1e-14; 1e-13 leaves 10x.
    curved = np.asarray(gfem.shape.quality(_chord_straight(octant)))
    straight = np.asarray(gfem.shape.quality(octant_straight))
    np.testing.assert_allclose(curved, straight, rtol=0, atol=1e-13)


def _one_tetrahedron(mesh):
    """The first tetrahedron of ``mesh`` alone, with the mesh's nodes."""
    t = mesh._topology
    empty = np.empty((0, 3), dtype=np.int64)
    alone = dataclasses.replace(
        t,
        volume_elements=t.volume_elements[:1],
        volume_tags=t.volume_tags[:1],
        volume_entities=t.volume_entities[:1],
        volume_midnodes=t.volume_midnodes[:1],
        surface_elements=empty,
        surface_tags=empty[:, 0],
        surface_entities=empty[:, 0],
        surface_neighbours=np.empty((0, 2), dtype=np.int64),
        surface_midnodes=empty,
        source=None,
    )
    return gfem.Mesh(mesh.nodes, alone)


@pytest.mark.filterwarnings("ignore:.*fell below")
def test_a_curved_tetrahedron_sampled_positive_but_bounded_nonpositive_warns(octant):
    # Seed 1: the mid nodes of tet 0 off their chord midpoints by 0.35 l in
    # random directions. Its scaled Jacobian is 0.038 at the 20 lattice points
    # (all positive, far from round-off) while the Bernstein bound of its
    # determinant is -4e-3 against 6 V ~ 6e-3: a fold, if any, is between samples.
    alone = _one_tetrahedron(octant)
    t = alone._topology
    nodes = np.array(alone.nodes)
    corners = nodes[t.volume_elements[0]]
    chord = np.array([(corners[a] + corners[b]) / 2 for a, b in _TET_EDGES])
    length = np.linalg.norm(corners[0] - corners[1])
    nodes[t.volume_midnodes[0]] = (
        chord + np.random.default_rng(1).normal(size=(6, 3)) * 0.35 * length
    )
    assert gfem.shape.quality(gfem.Mesh(nodes, t))[0] > 0
    with pytest.warns(gfem.MeshQualityWarning, match="between sample points"):
        alone.with_nodes(nodes)


