"""Curved (second-order gmsh) meshes: read, store, solve, round-trip and export.

Fixtures are in tests/unit/data (generated by make_curved_fixtures.py): the
octant of the unit sphere (size 0.2) and a quarter of a coaxial line (radii 1
and 2, length 1, size 0.5), each at order 1 and order 2 on the same geometry.
"""

