"""The scaling page: its tables are the committed snippets, from one commit's records.

docs/project/scaling.md reads no record at docs build time; `tools/scale_tables.py`
writes its snippets by hand. This checks the page's shape, not a number in it.
"""

import re
from pathlib import Path

import pytest

DOCS = Path(__file__).parents[2] / "docs"
PAGE = DOCS / "project" / "scaling.md"
SNIPPETS = sorted((DOCS / "project" / "_scaling").glob("*.md"))


def test_the_page_is_in_the_table_of_contents():
    assert "project/scaling" in (DOCS / "index.md").read_text()


#: Generated with the others but not rendered: the agreement table is a
#: developer's gate, not a reader's result.
UNRENDERED = "agreement.md"


def test_the_page_includes_every_snippet_but_the_agreement_table():
    included = re.findall(
        r"^```\{include\} _scaling/(.+)$", PAGE.read_text(), re.MULTILINE
    )
    assert sorted(included) == [s.name for s in SNIPPETS if s.name != UNRENDERED]
    assert UNRENDERED in [s.name for s in SNIPPETS]


@pytest.mark.parametrize("page", ["project/scaling.md", "verification.md"])
def test_no_page_a_user_reads_includes_the_agreement_table(page):
    assert UNRENDERED not in (DOCS / page).read_text()


@pytest.mark.parametrize("snippet", SNIPPETS, ids=lambda p: p.name)
def test_each_snippet_comes_from_one_commit_and_one_manifest(snippet):
    first = snippet.read_text().splitlines()[0]
    assert first.startswith("% Generated by tools/scale_tables.py")
    assert "commit 9a57680" in first


def test_every_snippet_names_the_same_records_manifest():
    digests = {re.findall(r"sha256 ([0-9a-f]{64})", s.read_text())[0] for s in SNIPPETS}
    assert len(digests) == 1


@pytest.mark.parametrize("private", [".scratch", "ticket", "ehpc", "resl", "/gpfs"])
def test_no_private_path_or_name_reaches_the_page(private):
    for path in (PAGE, *SNIPPETS):
        assert private not in path.read_text(), path.name


def test_the_page_makes_no_scaling_claim():
    text = PAGE.read_text().lower()
    opening = next(p for p in text.split("\n\n") if not p.startswith("#"))
    assert "observations" in opening
    assert "scales to" not in text
