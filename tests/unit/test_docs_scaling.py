"""The scaling page: committed snippets, each set from one commit's records.

docs/project/scaling.md reads no record at docs build time; `tools/scale_tables.py`
writes its snippets by hand. This checks the page's shape, not a number in it.
"""

import re
from pathlib import Path

import pytest

DOCS = Path(__file__).parents[2] / "docs"
PAGE = DOCS / "project" / "scaling.md"
SNIPPETS = sorted((DOCS / "project" / "_scaling").glob("*.md"))
#: Each scaling set's frozen commit, by its snippets' name prefix.
SETS = {"coarse-": "f199837", "pmg-": "bac84b3", "": "9a57680"}
#: Snippets whose run has not been made yet: each says so on its first line,
#: and leaves this set when its run writes it with its set's commit.
PENDING: set[str] = set()


def _commit(snippet: Path) -> str:
    return next(c for prefix, c in SETS.items() if snippet.name.startswith(prefix))


def test_the_page_is_in_the_table_of_contents():
    assert "project/scaling" in (DOCS / "index.md").read_text()


#: Generated with the others but not rendered: the agreement table is a
#: developer's gate, not a reader's result.
UNRENDERED = "agreement.md"


#: Where a snippet is read: GitHub renders its tables; the docs build does not.
LINK = "https://github.com/benvial/gfem/blob/main/docs/project/_scaling/"


def test_the_page_links_every_snippet_but_the_agreement_table_and_includes_none():
    text = PAGE.read_text()
    assert "{include}" not in text
    linked = set(re.findall(re.escape(LINK) + r"([\w-]+\.md)\)", text))
    assert linked == {s.name for s in SNIPPETS if s.name != UNRENDERED}
    assert UNRENDERED in [s.name for s in SNIPPETS]


def test_every_dof_count_in_the_summary_is_in_a_snippet():
    # The page copies its numbers from the snippets now that it no longer
    # includes them. The hand-written ranks-and-threads section is in no snippet
    # and sits between the summary and the reproduction section.
    summary = PAGE.read_text().split("## Ranks and threads")[0]
    counts = set(re.findall(r"\d{1,3}(?:,\d{3})+", summary))
    assert counts
    corpus = "\n".join(s.read_text() for s in SNIPPETS)
    assert [c for c in sorted(counts) if c not in corpus] == []


@pytest.mark.parametrize("page", ["project/scaling.md", "verification.md"])
def test_no_page_a_user_reads_includes_the_agreement_table(page):
    assert UNRENDERED not in (DOCS / page).read_text()


@pytest.mark.parametrize("snippet", SNIPPETS, ids=lambda p: p.name)
def test_each_snippet_comes_from_its_sets_commit(snippet):
    first = snippet.read_text().splitlines()[0]
    if snippet.name in PENDING:
        assert first.startswith("% PLACEHOLDER")
        return
    assert first.startswith("% Generated by tools/scale_tables.py")
    assert f"commit {_commit(snippet)}," in first


@pytest.mark.parametrize("commit", sorted(set(SETS.values())))
def test_every_snippet_of_a_set_names_the_same_records_manifest(commit):
    digests = {
        re.findall(r"sha256 ([0-9a-f]{64})", s.read_text())[0]
        for s in SNIPPETS
        if s.name not in PENDING and _commit(s) == commit
    }
    assert len(digests) == 1


@pytest.mark.parametrize("private", [".scratch", "ticket", "ehpc", "resl", "/gpfs"])
def test_no_private_path_or_name_reaches_the_page(private):
    for path in (PAGE, *SNIPPETS):
        assert private not in path.read_text(), path.name


def test_the_page_makes_no_scaling_claim():
    text = PAGE.read_text().lower()
    opening = next(p for p in text.split("\n\n") if not p.startswith("#"))
    assert "observations" in opening
    assert "scales to" not in text
